def calculate_kzi():
    total_kzi = 0.0
    results = []
    
    for group_name, group_data in DATA.items():
        R_j = group_data["R"]
        group_sum = 0.0
        
        for ind in group_data["indicators"]:
            status = st.session_state.get(f"{ind['id']}_status", "Не выполнено (0)")
            comment = st.session_state.get(f"{ind['id']}_comment", "")
            
            # Логика расчета: Полный вес, половина веса (компенсирующие меры) или 0
            if status == "Выполнено (1)":
                score = ind["weight"]
            elif status == "Частично (0.5)":
                score = ind["weight"] * 0.5
            else:
                score = 0.0
                
            group_sum += score
            results.append({
                "Группа": group_name,
                "Показатель": ind["id"],
                "Наименование": ind["name"],
                "Статус": status,
                "Балл": score,
                "Комментарий / Доказательство": comment
            })
            
        total_kzi += group_sum * R_j
        
    return round(total_kzi, 2), pd.DataFrame(results)

